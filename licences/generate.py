"""Writes the third-party licence files of Augmented View's plugin and server into this folder: plugin.txt and
server.txt. Run it from anywhere, with Python 3.8+ and cargo-about (`cargo install cargo-about --locked --features cli`),
after any change to a Cargo.lock:

    python licences/generate.py

Each file has up to three parts:
  1. the Rust crates the program is built from, with their licence texts (cargo-about, about.toml and about.hbs);
  2. the COPYRIGHT, AUTHORS and NOTICE files those crates' packages carry, copied in full;
  3. for the server, additional.txt: native code compiled in, data built in, and full licence texts that cargo cannot
     see (kept by hand; check it when a dependency named there changes).

`pack --release` ships server.txt beside the server as augmented-view-server-THIRD-PARTY-LICENSES.txt, with the
plugin's LICENSE, and refuses to release the server without them.

cargo-about may fetch a licence file from a crate's repository (the clarifications in about.toml). It fails, and
nothing is written, if a crate's licence is not in about.toml's `accepted` list or a clarified file has changed.
"""
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PLUGIN = os.path.dirname(HERE)

# The platform a release is built for. A build for another platform (or the Metal build on macOS, with
# --no-default-features --features metal) can link other crates: add its target here and regenerate.
NATIVE = ["x86_64-pc-windows-msvc"]
PROGRAMS = [
    # (file, manifest, targets, cargo features, what it is, append additional.txt)
    ("plugin.txt", "core/Cargo.toml", ["wasm32-unknown-unknown"], [],
     "Augmented View's Obsidian plugin (main.js, which holds augmented_view.wasm)", False),
    ("server.txt", "server/Cargo.toml", NATIVE, [], "augmented-view-server, Augmented View's model server (CUDA build)", True),
]
NOTICE_PREFIXES = ("NOTICE", "COPYRIGHT", "AUTHORS", "THIRD-PARTY", "THIRD_PARTY")

HEADER = """THIRD-PARTY LICENCES: {what}

Augmented View is released under the MIT licence; its text is in the file LICENSE that accompanies this one. The source
code of this version is at https://github.com/Gameboard-dev/obsidian-augmented-view (the release's tag), and the build
tool and shared crates at https://github.com/Gameboard-dev/obsidian-cargo-lib.

This file lists the work of others that this program contains, with the licence texts and copyright notices their
licences ask to be passed on. It was generated by licences/generate.py with cargo-about, for {targets}.

"""


def cargo_about(manifest, targets, features, *args):
    cmd = ["cargo", "about", "generate", "--fail", "--locked",
           "-c", os.path.join(HERE, "about.toml"), "-m", os.path.join(PLUGIN, manifest), "--target", *targets]
    if features:
        cmd += ["--features", " ".join(features)]
    cmd += list(args)
    run = subprocess.run(cmd, cwd=PLUGIN, capture_output=True, text=True, encoding="utf-8")
    if run.returncode != 0:
        sys.exit(f"cargo about failed for {manifest} (exit {run.returncode}):\n{run.stderr}")
    return run.stdout


def notices(listing):
    """Part 2: every COPYRIGHT, AUTHORS or NOTICE file in the packages of the crates cargo-about listed."""
    out, seen = [], set()
    for krate in sorted(listing["crates"], key=lambda c: (c["package"]["name"], c["package"]["version"])):
        pkg = krate["package"]
        key = (pkg["name"], pkg["version"])
        if key in seen:
            continue
        seen.add(key)
        root = os.path.dirname(pkg["manifest_path"])
        try:
            names = sorted(os.listdir(root))
        except OSError:
            continue
        for name in names:
            path = os.path.join(root, name)
            if not name.upper().startswith(NOTICE_PREFIXES) or not os.path.isfile(path):
                continue
            with open(path, encoding="utf-8", errors="replace") as f:
                text = f.read().strip("\n")
            out.append(f"{'=' * 80}\n{pkg['name']} {pkg['version']}: {name}\n{'-' * 80}\n{text}\n\n")
    head = ("PART 2. COPYRIGHT, AUTHORS AND NOTICE FILES\n\n"
            "The COPYRIGHT, AUTHORS and NOTICE files in the packages of the crates in Part 1, in full. No crate here ships\n"
            "an Apache-2.0 NOTICE file unless one is listed below.\n\n")
    return head + ("".join(out) if out else "None of the crates in Part 1 carries such a file.\n\n")


def main():
    with open(os.path.join(HERE, "additional.txt"), encoding="utf-8") as f:
        additional = f.read()
    template = os.path.join(HERE, "about.hbs")
    for file, manifest, targets, features, what, extra in PROGRAMS:
        body = cargo_about(manifest, targets, features, template)
        listing = json.loads(cargo_about(manifest, targets, features, "--format", "json"))
        text = HEADER.format(what=what, targets=", ".join(targets)) + body.strip("\n") + "\n\n\n" + notices(listing)
        if extra:
            text += "\n" + additional
        with open(os.path.join(HERE, file), "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print(f"{file}: {len(listing['crates'])} crates, {len(text) // 1024} KB")


if __name__ == "__main__":
    main()
